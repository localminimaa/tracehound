// A server-written title in the interface language, or as it came when no pattern knows it
function tf(s) {
  if (LI === undefined || !s) return s;
  const exact = tr(s);
  if (exact) return exact;
  for (const [re, ...to] of FINDINGS) if (re.test(s)) return s.replace(re, to[LI]);
  return s;
}

// Swap static text in place: text nodes whose whole (trimmed) text is in the table, and the title / placeholder
// attributes. Code, logs and user input are left alone.
const SKIP = new Set(["SCRIPT", "STYLE", "CODE", "PRE", "TEXTAREA"]);
function trNode(n) {
  if (n.nodeType === 3) {
    const raw = n.nodeValue, key = raw.trim();
    if (!key || SKIP.has(n.parentNode?.nodeName)) return;
    const v = tr(key);
    if (v !== undefined && v !== key) n.nodeValue = raw.replace(key, v);
    return;
  }
  if (n.nodeType !== 1) return;
  for (const a of ["title", "placeholder", "alt"]) {
    const v = n.getAttribute(a);
    const x = v && tr(v.trim());
    if (x) n.setAttribute(a, x);
  }
  if (!SKIP.has(n.nodeName)) for (const c of n.childNodes) trNode(c);
}
if (LI !== undefined) {
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : LANG;
  trNode(document.body);
  new MutationObserver((ms) => {
    for (const m of ms) {
      if (m.type === "characterData") trNode(m.target);
      else if (m.type === "attributes") trNode(m.target);
      else for (const n of m.addedNodes) trNode(n);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["title", "placeholder"] });
}
